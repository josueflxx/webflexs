import { createRequire } from 'node:module';
import assert from 'node:assert/strict';
const require = createRequire('C:/Users/Brian/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/package.json');
const { chromium } = require('playwright');
const browser = await chromium.launch({executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true, args:['--enable-unsafe-swiftshader']});
const page = await browser.newPage({viewport:{width:1440,height:1000}});
await page.route('https://**', route => route.abort());
const errors = [];
const assets = [];
page.on('pageerror', e => errors.push(e.message));
page.on('request', r => { if (/model-viewer|\.glb/.test(r.url())) assets.push(r.url()); });
await page.goto('http://127.0.0.1:8772', {waitUntil:'networkidle'});
assert.equal(assets.length, 0, '3D assets must not load before opening');
await page.locator('#width_mm').fill('140');
assert.match(await page.locator('#clampCalculatedDesc').innerText(), /140/);
await page.locator('#clampShow3d').click();
await page.waitForFunction(() => document.querySelector('model-viewer')?.loaded, {timeout:30000});
await page.locator('#clamp3dReset').waitFor({state:'visible'});
const model = page.locator('model-viewer');
const initial = await model.evaluate(el => ({...el.getCameraOrbit()}));
const box = await model.boundingBox();
await page.mouse.move(box.x + box.width * .5, box.y + box.height * .5);
await page.mouse.down();
await page.mouse.move(box.x + box.width * .75, box.y + box.height * .60, {steps:15});
await page.mouse.up();
await page.waitForTimeout(600);
const rotated = await model.evaluate(el => ({...el.getCameraOrbit()}));
assert.ok(Math.abs(rotated.theta - initial.theta) > .1, 'drag rotates the model');
await page.mouse.wheel(0, -180);
await page.waitForTimeout(600);
const zoomed = await model.evaluate(el => ({...el.getCameraOrbit()}));
assert.ok(zoomed.radius < rotated.radius, 'wheel zooms in');
await page.locator('#clamp3dReset').click();
await page.waitForTimeout(600);
await page.locator('.clamp-simulator-card').screenshot({path:'output/clamp-3d-desktop.png'});
await page.locator('#clampShowDrawing').click();
assert.equal(await page.locator('#clampDrawing').isVisible(), true);
await page.locator('#clampShow3d').click();
assert.equal(assets.filter(u => u.endsWith('.glb')).length, 1, 'reuse loaded model');
await page.setViewportSize({width:390,height:844});
await page.locator('#clampShow3d').scrollIntoViewIfNeeded();
await page.waitForTimeout(300);
assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, 'no mobile overflow');
await page.locator('.clamp-simulator-card').screenshot({path:'output/clamp-3d-mobile.png'});
assert.deepEqual(errors, []);
const errorPage = await browser.newPage();
await errorPage.route('https://**', route => route.abort());
await errorPage.route('**/*.glb*', route => route.abort());
await errorPage.goto('http://127.0.0.1:8772');
await errorPage.locator('#clampShow3d').click();
await errorPage.locator('#clamp3dRetry').waitFor({state:'visible'});
await errorPage.locator('#clampShowDrawing').click();
assert.equal(await errorPage.locator('#clampDrawing').isVisible(), true);
await errorPage.unroute('**/*.glb*');
await errorPage.locator('#clampShow3d').click();
await errorPage.waitForFunction(() => document.querySelector('model-viewer')?.loaded);
console.log(JSON.stringify({passed:true, assets, initial, rotated, zoomed, errors}));
await browser.close();
